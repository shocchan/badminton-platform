// 種目別の恒常ページの定義（2026-08-24 新設）。
//
// 【なぜ作るか】
// 大会は開催が終わるとトップの一覧から消える。つまり**開催するほど資産が消えていく**。
// 「ミックスダブルス 大会 埼玉」のような種目＋地域の検索に、恒常的な受け皿が1つも無かった
// （Search Console 実測でこの種の検索語は表示0件）。
//
// 【設計】
// - 種目ごとに1ページ。開催予定があれば上に出し、過去の開催は**畳んで**下に置く。
//   トップの一覧は今までどおり「開催予定だけ」＝過去大会で見えづらくしない
// - 説明文（費用・持ち物・申込方法）は**すでにサイトで公表している事実だけ**。
//   FAQページの記載と同じ内容にしてある。ここを直すときは FaqPage も見ること
// - **参加人数は出さない。** 実績が薄い時期に「参加0人」と出すのは、正直だが誰も得しない。
//   開催した事実（日付・会場・レベル）だけを積み上げる
export type TournamentTypeSlug = 'singles' | 'doubles' | 'mixed-doubles';

