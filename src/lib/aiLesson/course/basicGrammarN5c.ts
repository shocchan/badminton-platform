// 初級文法（N5）バッチC：て形まわり と ない形・た形まわり の18項目。
//
// カバー範囲:
// - n5g-unit-5「て形と依頼・許可」9項目
//   動詞て形のつくり方 / 〜てください / 〜ています（進行）/ 〜ています（状態・習慣）/
//   〜てもいいです / 〜てはいけません / 〜てから / 〜前に / 〜あとで
// - n5g-unit-6「ない形・た形」9項目
//   動詞ない形 / 〜ないでください / 〜なければなりません / 〜なくてもいいです /
//   動詞た形 / 〜たことがあります / 〜たり〜たりします / 〜たいです / 〜ましょう・〜ませんか
//
// この2ユニットは「です/ます・助詞」の次に来る、初級最大の山場。て形が固まらないと
// 「〜ています」「〜てから」「〜てはいけません」が全部詰まり、た形が固まらないと
// 「〜たことがあります」「〜たり」「〜たら」が積めない。そのため て形／た形／ない形は
// 「変化のつくり方」そのものを1項目として独立させ、派生文型より先に置いている。
//
// 活用の基準形は**ます形に統一**する（2026-08-17 レビュー反映）。
// 直前の N5a・N5b で扱ったのは です／ます・助詞・形容詞だけで、辞書形はまだ出てこない
// （辞書形の項目は N4c が初出）。そのため て形・た形・ない形・〜たい・〜ましょう は
// すべて「ます形の最後の音」から導く。動詞のⅠ・Ⅱ・Ⅲ類の見分け方も、この判定に必要なので
// n5g-te-form（unit-5 の1項目め）の中で先に説明する。
// 例外的に辞書形／た形を必要とする2項目には、その場で最小限の橋渡しを書いている:
// - n5g-maeni（前に＋辞書形）→ ます形から辞書形の作り方を explanationZh に併記
// - n5g-atode（あとで＋た形）→ た形は「て形の『て』を『た』に換えるだけ」と明示
//
// 中国語話者向けの重点（commonMistakesZh / learnerFocus に反映）:
// - 動詞のⅠ類／Ⅱ類の見分け（ます形が え段＝Ⅱ類／い段は原則Ⅰ類だが少数のⅡ類がある）
// - て形の音便（い・ち・り→って ／ み・び・に→んで）と「行きます→行って」の例外
// - 「今〜ます」（これからの予定）と「今〜ています」（進行中）の取り違え
// - 「前に＋辞書形」「あとで＋た形」の時制ルール（母語に時制標識がないため崩れやすい）
// - 「〜てはいけません（禁止）」と「〜なければなりません（義務）」の読み違い
// - 「〜たい」は第三者に使えない／い形容詞として活用する
//
// すべて自作。既存教材・市販書籍の文面は使わない。
