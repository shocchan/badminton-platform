/** タグの根拠。**弱い根拠を強い根拠と同じ顔で出さない**ためにある */
export type TagSource = 'surface' | 'definition' | 'collocation';
export type TagConfidence = 'strong' | 'weak';

export interface DomainTag {
  domain: PracticalDomain;
  confidence: TagConfidence;
  /** 何に当たったか（人が確かめるときの手がかり） */
  via: string;
  source: TagSource;
}

export interface SituationTagged {
  situation: SituationTag;
  via: string;
  source: TagSource;
}

