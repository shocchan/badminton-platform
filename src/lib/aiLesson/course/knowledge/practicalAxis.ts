/**
 * Practical Axis — 「どこで／何をする」で語彙を引けるようにする（2026-09-10 Phase 2-1）。
 *
 * 【なぜ要るか】
 * いま語彙は**級（JLPT Axis）でしか引けない**。「N3の単語を勉強する」はできても、
 * 「病院で必要な日本語」「会社で依頼するときの日本語」では引けない。
 * 日本で暮らしている学習者が本当に欲しいのは後者のほうなので、軸をもう1本足す。
 *
 * 【設計の要：既存データを1語も書き換えない】
 * 語彙4,697語は wordId を持っており、学習履歴・図鑑・錯題本がそのIDを参照している。
 * タグを語彙データへ書き込むと、教材ファイル40本を全部書き換えることになり、
 * 差分も読めなくなる。**IDを参照する別レイヤー**として持つ。
 *
 * 【いちばん気をつけたこと：例文の言葉に釣られない】
 * 実データで確認したところ、こういう誤判定が起きる:
 *   「兄」  例文=「兄は東京で**働いて**います」 → work と判定されかねない
 *   「頭」  例文=「頭が痛いので**薬**を飲みます」 → health は妥当
 * 前者は家族の語で、例文がたまたま仕事に触れているだけ。
 * だから**根拠の強さを分けて記録する**:
 *   strong … 見出し語そのものが分野語（病院・会社・駅）
 *   weak   … 例文や連語にしか出ない（人が見て確かめる対象）
 * 弱い根拠を強い根拠と同じ顔で出さない。QAで「怪しいタグ」として数えられる。
 */

/**
 * 分野。**場所や場面**で切る（品詞や意味分類では切らない）。
 * 学習者が「いま、そこで困っている」単位に合わせる。
 *
 * 2026-09-10: 最初の8分野に food と money を足した。実データを見ると
 * 飲食（注文・会計）と金銭（支払い・銀行）が生活語彙の大きな塊で、
 * shopping に混ぜると「レストランで注文する」が引けなくなるため。
 */
export type PracticalDomain =
  | 'shopping'    // 買い物・店
  | 'food'        // 飲食店・食事
  | 'work'        // 仕事・会社
  | 'health'      // 病院・体調
  | 'government'  // 役所・手続き
  | 'transport'   // 交通・移動
  | 'housing'     // 住まい・不動産
  | 'school'      // 学校・勉強
  | 'social'      // 人づきあい・日常のやりとり
  | 'money';      // お金・支払い・銀行

/**
 * 場面でやること。分野（どこで）と組み合わせて「会社で依頼する」を作る。
 * **動作**なので、名詞よりも動詞・表現に付きやすい。
 */
