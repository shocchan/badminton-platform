// 方針（kanjiTypes.ts の鉄則に従う）:
// - 読み・訳・例語・注記はすべて自社で書き起こした。他ソースの音訓表・訳文・例文は写していない。
// - onyomi / kunyomi は「常用漢字表にある読みのうち、N4段階で実際に必要な主要な読み」だけを載せる。
//   稀用の読み（例: 病の「ヘイ」、要の「かなめ」以外の派生）は学習者を混乱させるので載せない。
// - 画数・部首は1字ずつ数えて確かめた。自信の持てない字は最初から入れていない。
// - chineseNote / mnemonicZh / meaningZh / glossZh は簡体字中国語。日本語は必ず「」で引用する。
// - 中国語母語者は漢字の意味を既に知っているので、注記は「読み」「日中の字形差・意味差」
//   「日本語独自の使い方」に重心を置く（意味当てのための説明にはしない）。
//
// ■ テーマ外として入れなかった字
//   「出」「行」「金」「気」「口」などは N5 帯（バッチA〜D）に入るので重複させない。
//   当初案にあった「用」「者」は kanjiN4b（仕事・学校）が先に収録していたため本バッチから外し、
//   同じ生活・手続き圏の「引」（お金を引き出す・引っ越す）「返」（借りた物を返す）に差し替えた。
//   問題キーは `kanji-<aspect>:<char>:<i>` で字がキーになるため、
//   同じ字が2バッチに入ると台帳・错题本のキーが衝突する。重複は必ず避ける。
//
// ■ 例語の裏取り
//   `inVocabBank` は層C語彙バンク（ALL_VOCAB_CONTENT の active_beta）に同じ見出しが
//   実在するかを実測して入れた値。false の6語（「住む」「必要」「必ず」「病院」「薬」「銀色」）は
//   バンクに無いため訳をこのファイルで新規に書き起こしている。
import type { KanjiEntry, KanjiRadical, KanjiWord } from './kanjiTypes';

const BATCH_ID = 'n4a';

let seq = 0;

const rad = (form: string, readingJa: string, meaningZh: string): KanjiRadical =>
  ({ form, readingJa, meaningZh });

/** 例語。第4引数は層C語彙バンク（active_beta）に同じ見出しが実在するか */
const w = (surface: string, reading: string, glossZh: string, inVocabBank: boolean): KanjiWord =>
  ({ surface, reading, glossZh, inVocabBank });

/** 1字分。level は本バッチ全字 N4 */
const k = (
  character: string,
  onyomi: string[],
  kunyomi: string[],
  meaningZh: string,
  strokeCount: number,
  radical: KanjiRadical,
  words: KanjiWord[],
  chineseNote: string,
  mnemonicZh: string,
): KanjiEntry => {
  seq += 1;
  return {
    entryId: `kj-${BATCH_ID}-${String(seq).padStart(2, '0')}`,
    character, onyomi, kunyomi, meaningZh, strokeCount, radical,
    level: 'N4', words, chineseNote, mnemonicZh,
    state: 'active_beta', reviewNotes: [], batchId: BATCH_ID,
  };
};

