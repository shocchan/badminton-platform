// 【なぜ足したか】
// 既存のN5バッチA〜Dは100字あるが、標準的なJLPT N5リストと突き合わせると
// **最頻出の12字が抜けていた**（本・間・東・今・北・午・西・語・何・南・毎・白）。
// 「日本語」「今日」「午前」「何時」——初級で毎日出る語が、漢字モジュールで
// 一度も扱われない状態だった。ひらがなしか読めない学習者にとっては
// 「教材のどこかで必ず見るのに、教わる場所が無い字」になる。
//
// 【この12字の選び方】
// 標準N5リストにあってバンクに無い字だけ。増やしすぎず、穴をふさぐことに徹する。
//
// 【中国語話者向け注記の方針】
// 既存バッチと同じく、**字形の差・意味のずれ・日本語独自の使い方**を具体的に書く。
// 中国語と同形同義なら「読みだけが問題」と言い切る。
import type { KanjiEntry, KanjiRadical, KanjiWord } from './kanjiTypes';
import { promoteKanjiBatch } from './kanjiTypes';

const BATCH_ID = 'n5e';

let seq = 0;

const rad = (form: string, readingJa: string, meaningZh: string): KanjiRadical =>
  ({ form, readingJa, meaningZh });

/** 例語。第4引数は層C語彙バンク（active_beta）に同じ見出しが実在するか */
const w = (surface: string, reading: string, glossZh: string, inVocabBank: boolean): KanjiWord =>
  ({ surface, reading, glossZh, inVocabBank });

const k = (
  character: string,
  onyomi: string[],
  kunyomi: string[],
  meaningZh: string,
  strokeCount: number,
  radical: KanjiRadical,
  words: KanjiWord[],
  chineseNote: string,
  mnemonicZh: string,
): KanjiEntry => {
  seq += 1;
  return {
    entryId: `kj-${BATCH_ID}-${String(seq).padStart(2, '0')}`,
    character, onyomi, kunyomi, meaningZh, strokeCount, radical,
    level: 'N5', words, chineseNote, mnemonicZh,
    state: 'draft', reviewNotes: [], batchId: BATCH_ID,
  };
};

