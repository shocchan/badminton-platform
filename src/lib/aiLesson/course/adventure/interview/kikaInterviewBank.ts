//
// 逆算の設計（面接で落ちる原因 → 鍛える力）:
//   ① 申請書類と答えが食い違う        → 自分の事実を正確に言う練習（暗記ではなく自分の答え）
//   ② 質問が聞き取れない・答えられない  → 質問文に慣れる（言い換えverbal含む）
//   ③ 動機が浅い・借り物っぽい         → 自分ノート（気持ちの整理→伝える言い方）
//   ④ 違反・入金など答えにくい話題で動揺 → 「正直に・簡潔に・改善を添える」の型
//   ⑤ 練習不足で本番に緊張            → 声に出す練習の記録＋先生との模擬面接
//
// 大原則（画面にも出す）: **回答例を丸暗記させない。**
// 面接官は申請書類を見ながら聞くので、借り物の答えは矛盾で崩れる。
// 回答例は「長さ・構成・トーン」の参考であり、中身は必ず本人の事実に置き換える。
//
// 質問文は日本語のまま（面接が日本語だから）。zhは「何を聞かれているか」の補助のみ。

