// 初級文法 ギャップ補充バッチF（5項目）。2026-08-18 新設。
//
// 【なぜ作ったか】
// 既存の初級文法108項目（N5a〜c／N4a〜d）を洗い出したところ、日本で生活する学習者が
// 毎週使うのに**項目として一度も立っていない**初級文法が残っていた。この5つがそれ。
//   1. 〜とか／〜など … 「例を挙げる」表現が無い。既存の「など」8ヒットはすべて例文中の語で、
//      学ぶ対象になっていなかった。会話の「とか」と書面の「など」は使い分けが必要。
//   2. 〜ずつ … 配布・分配（一人2枚ずつ）と段階的変化（少しずつ）。学校・区役所の案内文の常連。
//   3. 〜始めます／〜終わります／〜続けます … 「ます形に動詞を後接させて意味を足す」という
//      作り方そのものが1項目も無かった。〜方・〜すぎる・〜やすい と同じ族なので、
//      ここを立てると同じ形で作れる語がまとめて増える（生産性が跳ね上がる）。
//   4. 〜さ（形容詞の名詞化）… 既存の n4g-koto-no-nominalize は**文**の名詞化。
//      形容詞の名詞化（高さ・広さ・便利さ）は別枠で、家具・荷物・部屋・健康診断で必ず要る。
//   5. 〜たがっています … n5g-tai-desu（自分の願望）はあるのに、第三者の願望を言う形が無い。
//      中国語には一人称と三人称で願望表現を変えるという発想が無いため、
//      「子どもが行きたいです」という誤りが定着したまま残る。
//
// 【unit の割り当て理由】（新規unitは作らない。既存の束IDに寄せる）
// - n4g-unit-8「文をつなぐ・言いかえる」← 〜とか／〜など・〜ずつ・〜さ
//   この束は既に 〜し／〜だけ・〜しか／〜という／〜こと・〜の（名詞化）を持つ、
//   「単文を長くする／限定する／言いかえる道具」の束。例示（とか・など）と
//   数量の配分（ずつ）は同じ副助詞の仲間で、形容詞の名詞化（さ）は
//   n4g-koto-no-nominalize の真横に置くのが学習順として自然。
// - n4g-unit-6「て形＋補助動詞」← 〜始めます／〜終わります／〜続けます
//   この束は「動詞に別の動詞を後接させて意味を足す」束。既存はて形接続だけだったので、
//   ます形接続の族をその隣に置き、contrast で接続の違いを毎回対比させる。
// - n4g-unit-5「伝聞・推量」← 〜たがっています
//   この束の本質は「他人のことを直接は言い切れないので、形を変えて述べる」。
//   〜そうです（様態）・〜ようです と同じ制約から出てくる形なので、ここに入れる。
//   ※ 新しい unit を作らなかったのは、basicGrammarChunks.ts の N4_UNIT_IDS が
