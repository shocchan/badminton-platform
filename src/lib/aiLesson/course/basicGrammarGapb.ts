//   1. 〜ぐらい／〜ごろ … 「ぐらい」「くらい」「ごろ」が全ファイルで0ヒット。
//      待ち合わせ・値段・所要時間で毎日使う。量の「ぐらい」と時点の「ごろ」の
//      取り違えは中国語話者に非常に多い（中国語はどちらも「大概／左右」で済む）。
//   2. 動詞のグループ分け … Ⅰ類/Ⅱ類/Ⅲ類という語は n5g-te-form・n5g-nai-form・
//      n5g-ta-form・n4g-kanoukei の formation の中に埋め込まれているだけで、
//      **判別そのものを練習・復習・再テストできる項目が無かった**。
//      て形・ない形・た形・可能形・受身・使役の全部がこの判別に依存するので、
//      ここが空いていると下流の活用が連鎖的に崩れる。単独項目として立てる。
//   3. 辞書形とます形の対応 … 辞書形の初出は N4c の n4g-futsuukei（普通形）で、N5に無い。
//      実装はます形起点で組んであるため、学習者は辞書・翻訳アプリ・求人票・薬の説明・
//      注意書きに出る辞書形を自力でます形へ戻せない。自習の自立度に直結する。
//   4. 数量詞の位置 … 中国語は「买三个苹果」で名詞の前に付くため「3つのりんごを買います」と
//      直訳しがち。買い物・注文で毎日使う語順なのに扱いが無かった。
//   5. 疑問詞＋か／も … 「だれか」「なにか」「どこにも」が0ヒット。n5g-gimonshi は
//      疑問詞そのものだけ。中国語の「什么」が疑問と不定を兼ねるため、「か」と「も」の
//      付け分けが習得されないまま残る。
//   6. もう〜ました／まだ〜ていません … 完了・未完了の対が無い。否定側が
//      「まだ〜ていません」（×まだ〜ませんでした）になる点は最頻出の誤り。
//      書類提出・支払い・受け取りの確認会話で毎日使う。
//   7. 〜が／〜けど（逆接・前置き）… 逆接の「が」「けど」が項目として無い
//      （n4g-noni は不満の逆接、n4g-temo は譲歩で別物）。これが無いと文が全部言い切りになり、
//      「すみませんが」「安いけど、遠いです」が言えず、日本語がきつく聞こえる。
