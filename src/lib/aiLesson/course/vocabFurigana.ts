/** 設定＋文脈→表示モード（§13）。first_timeは「初回・弱点」判定を呼び出し側から受ける */
export const resolveFuriganaMode = (
  setting: 'always' | 'first_time' | 'hard_only' | 'off',
  ctx: { isFirstTime?: boolean; isWeak?: boolean },
): FuriganaDisplayMode => {
  if (setting === 'always') return 'all';
  if (setting === 'first_time') return ctx.isFirstTime || ctx.isWeak ? 'all' : 'hard';
  if (setting === 'hard_only') return ctx.isWeak ? 'all' : 'hard';
  return 'none';  // off でも詳細画面の「読みを表示」補助操作は残す（アクセシビリティ・§13）
};

/** plain / 読みつき / 難読（hard_only設定で表示） / 対象語 */
