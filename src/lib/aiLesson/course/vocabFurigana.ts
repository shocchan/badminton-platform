export interface FuriganaCoverage { total: number; withSegments: number; withoutSegments: string[]; segmentCount: number }
/** カバレッジ集計（docs・完了報告用の単一関数・手計算禁止） */
export const furiganaCoverage = (itemIds: string[]): FuriganaCoverage => {
  const withoutSegments = itemIds.filter((id) => !EXAMPLE_FURIGANA[id]);
  const segmentCount = itemIds.reduce((n, id) => n + (EXAMPLE_FURIGANA[id]?.length ?? 0), 0);
  return { total: itemIds.length, withSegments: itemIds.length - withoutSegments.length, withoutSegments, segmentCount };
};
