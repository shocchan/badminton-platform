// CEO指示（2026-08-25）:
//   「訳して投稿っていうよりかは右上の言語変更したときに、ブログ文章も中国語に切り替わるように」
//   「固有名詞とかはそのままで！変に訳しちゃだめね」
//
// 会場名・大会名・店名・人名は**日本語表記のまま**残す。
// 中国語話者が会場を検索したり、受付で名前を見せたりするときに、
// 訳した名前は現地で1文字も役に立たないため（例: 芝園公民館 → 「芝园公民馆」では地図に出ない）。
// 初出のみ括弧で読み方や意味を補ってよい。

/**
 * 日本語のまま残す語。
 * 追加するときの基準は「その表記のまま現地で通じる必要があるか」。
 * 通じる必要がある（地図・受付・店名・人名）なら残す。
 */
export const KEEP_JA = [
  // 会場
  '芝園公民館', '蕨市民体育館', '戸田市スポーツセンター', '川口市立戸塚スポーツセンター',
  // 地名・駅名・路線名（地図と乗換案内でそのまま使える表記でないと意味がない）
  '川口', '蕨', '西川口', '戸田', '蕨駅', 'JR京浜東北線',
  // 大会・団体・店
  '川口・蕨バド交流杯', '川口・蕨バドミントン交流杯', '川口・蕨バド交流大会',
  '火瓶杯', 'kawabado', 'ばりかた屋', 'マミーマート',
  // 参加者の所属クラブ（本人たちが名乗っている表記をそのまま出す）
  'メガネクラッシュズ', 'チームワイ', 'Garuda Kanagawa BC', 'YBBC',
  // 主催・協力
  '株式会社中日文化交流諮詢',
  // 用具・規格
  '第2種検定球',
  // 人名
  'しょっちゃん',
];

/**
 * 「訳してはいけない語」のうち**仮名を含むもの**。
 * 中国語の地の文に仮名があると advLanguageIntegrity の unquoted_kana_in_zh に当たるので、
 * 検査の前にこれらを伏せる（＝許可リスト）。
 */
export const KEEP_JA_WITH_KANA = KEEP_JA.filter((w) => /[ぁ-ゟァ-ヺ]/.test(w));

/**
 * 中国語側の正式名称。サイトの他の中国語文言（src/pages/blogSeo.ts・
 * scripts/generate-worker.mjs の ORG_JSONLD alternateName）と同じ表記に揃える。
 * 団体名は既に中国語名が公開されているので、ここだけ日本語に戻すと表記が割れる。
 */
export const ORG_NAME_ZH = '川口・蕨羽毛球交流会';

/**
 * 用語の統一（簡体字）。訳文がこの表記になっているかをテストで見る。
 * 「單打」「羽球」などの繁体字・台湾表記が混ざると、同じ記事の中で表記が割れる。
 */
export const TERMS = {
  シングルス: '单打',
  ダブルス: '双打',
  ミックスダブルス: '混合双打',
  バドミントン: '羽毛球',
  初級: '初级',
  中級: '中级',
  上級: '高级',
};

/** 混ざってはいけない繁体字・台湾表記（簡体字で統一する） */
export const FORBIDDEN_VARIANTS = ['單打', '雙打', '羽球', '初級', '中級', '高級', '網前', '發球'];

/** 文字列から「訳してはいけない語」を伏せる（長いものから消す） */
export const stripKeepJa = (text) => {
  let out = text;
  for (const w of [...KEEP_JA].sort((a, b) => b.length - a.length)) out = out.split(w).join('');
  return out;
};
